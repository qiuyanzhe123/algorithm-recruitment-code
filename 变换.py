import cv2
import matplotlib.pyplot as plot
import numpy as np
qyz0=cv2.imread("test.jpg")
qyz=cv2.cvtColor(qyz0,cv2.COLOR_BGR2RGB)
qyz1=cv2.resize(qyz,None,fx=0.05,fy=0.05)
qyz2=cv2.resize(qyz,(1000,500))
qyz3=cv2.rotate(qyz,cv2.ROTATE_90_CLOCKWISE)
h1,w1=qyz.shape[:2]
m1=np.float32([[1,0,400],[0,1,200]])
qyz4=cv2.warpAffine(qyz,m1,(w1,h1))
qyz5=cv2.flip(qyz,1)
plot.figure(figsize=(10,6))
plot.subplot(2,3,1)
plot.imshow(qyz)
plot.title("Original")
plot.axis("off")
plot.subplot(2,3,2)
plot.imshow(qyz1)
plot.title("1")
plot.axis("off")
plot.subplot(2,3,3)
plot.imshow(qyz2)
plot.title("2")
plot.axis("off")
plot.subplot(2,3,4)
plot.imshow(qyz3)
plot.title("3")
plot.axis("off")
plot.subplot(2,3,5)
plot.imshow(qyz4)
plot.title("4")
plot.axis("off")
plot.subplot(2,3,6)
plot.imshow(qyz5)
plot.title("5")
plot.axis("off")
plot.savefig("test2_2.jpg",dpi=150)
plot.show()


